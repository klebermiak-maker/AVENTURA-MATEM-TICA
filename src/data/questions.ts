// Helper to get questions for phase & level, shuffled with procedural fallback for infinite play
export function getQuestionsForPhase(
  phaseId: number,
  level: DifficultyLevel,
  count = 8
): ProblemQuestion[] {
  let pool = QUESTIONS_BANK.filter((q) => q.phaseId === phaseId && q.level === level);
  if (pool.length === 0) {
    pool = QUESTIONS_BANK.filter((q) => q.phaseId === phaseId);
  }
  const shuffled = [...pool].sort(() => Math.random() - 0.5);

  const result = shuffled.slice(0, count);

  // If more questions needed than curated pool, fill with freshly generated procedural questions
  while (result.length < count) {
    result.push(generateProceduralQuestion(phaseId, level));
  }

  return result;
}

